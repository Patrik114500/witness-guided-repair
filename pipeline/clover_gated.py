"""Clover NL->spec pipeline + OUR key-free completeness gate, on CloverBench.
 Clover's gen_spec_from_doc generates a postcondition from the NL doc.
 B0 (Clover):      take the generated spec as-is.
 B1 (Clover+ours): measure key-free completeness (Dafny exec, reference = Clover's own gen_body_from_spec);
                   if weak (< THR), ask Clover to strengthen & re-generate.
 Eval (ground truth, deterministic): does the final generated spec IMPLY CloverBench's strong spec?
   reliable := the implication lemma verifies. This is NOT used as the gate signal (key-free), only to score.
 Metrics per arm: reliable, key-free c, llm_calls, time.
"""
import os, sys, re, json, glob, time
sys.path.insert(0, os.path.expanduser("~/clover/clover"))   # clover.py + direct_cache/sys_prompts/llm_cache
sys.path.insert(0, os.path.expanduser("~/clover/shim"))     # shim FIRST (shadow real sglang)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sglang as sgl
from sglang import OpenAI, set_default_backend
import clover
import vericode_compete as V
import dafny_mut as DM  # program-mutation completeness (type-general, MutDafny-style)

# decoupled models: the SPEC is generated by SPEC_MODEL (can be weak -> weak specs);
# the gate's REFERENCE implementation is generated by BODY_MODEL (keep strong so c is measurable).
SPEC_MODEL = os.environ.get("SPEC_MODEL", os.environ.get("SHIM_MODEL", "qwen2.5-coder:32b"))
BODY_MODEL = os.environ.get("BODY_MODEL", SPEC_MODEL)
def use_spec_model(): set_default_backend(OpenAI(SPEC_MODEL))
def use_body_model(): set_default_backend(OpenAI(BODY_MODEL))
use_spec_model()

DAFNY = os.path.expanduser("~/dafny/dafny/dafny")
CB = os.path.expanduser("~/clover/dataset/CloverBench/textbook_algo")
THR = float(os.environ.get("THR", "0.8"))
GATE_ROUNDS = int(os.environ.get("GATE_ROUNDS", "2"))


def ens_only(spec):
    """extract just the 'ensures ...' lines from a generated spec blob, dropping trailing ';' (Dafny
    predicates have no statement terminator; some models emit one, which breaks the completeness predicate)."""
    lines = re.findall(r"ensures[^\n]*", spec)
    return "\n    ".join(re.sub(r";\s*$", "", l).rstrip() for l in lines)


def load_task(name):
    d = os.path.join(CB, name)
    doc = open(os.path.join(d, name + "_spec.txt")).read().strip()
    strong = open(os.path.join(d, name + "_strong.dfy")).read()
    m = re.search(r"(method\s+\w+\s*\([^)]*\)\s*returns\s*\([^)]*\)(?:\s*requires[^\n]*)*)", strong)
    if not m:
        return None
    head = m.group(1).rstrip()
    # cut the method body before extracting ensures (else the last ensures swallows the body `{...}`)
    last_kw = max(strong.rfind("ensures"), strong.rfind("requires"))
    bpos = strong.find("{", last_kw) if last_kw >= 0 else -1
    spec_part = strong[:bpos] if bpos > 0 else strong
    gt_ens = V.ensures_list(spec_part)
    if not gt_ens:
        return None
    # parts: vc-spec carries GROUND-TRUTH ensures (the intended spec, used only for scoring + sig parse)
    parts = {"vc-preamble": "", "vc-helpers": "", "vc-code": "", "vc-postamble": "", "vc-description": doc,
             "vc-spec": head + "\n  " + "\n  ".join("ensures " + e for e in gt_ens)}
    return doc, head, parts


def reliable_gt(parts, gen_ens_lines):
    """does the generated spec IMPLY the benchmark's intended (strong) spec? deterministic."""
    sig = V.parse_sig(parts["vc-spec"])
    if not sig:
        return None
    name, params, ret = sig
    args = list(params) + ([ret] if ret else [])
    our = V.ensures_list("method _() returns ()\n  " + gen_ens_lines)
    orig = V.ensures_list(parts["vc-spec"])
    if not our or not orig:
        return None
    reqs = re.findall(r"requires\s+(.+)", parts["vc-spec"])
    lem = "lemma GTcheck(%s)\n" % ", ".join("%s: %s" % (n, t) for n, t in args)
    for r in reqs:
        lem += "  requires %s\n" % r
    for e in our:
        lem += "  requires %s\n" % e
    for e in orig:
        lem += "  ensures %s\n" % e
    lem += "{}\n"
    try:
        ok, _ = V.dverify(lem)
        return ok
    except Exception:
        return None


def clover_body(head, gen_ens_lines):
    """Clover's own code-from-spec: reference impl for the key-free gate. Returns a verified method or None."""
    full_spec = head + "\n    " + gen_ens_lines
    try:
        use_body_model()
        res = clover.gen_body_from_spec(full_spec, DAFNY, feedback_turn=3)
    except Exception:
        return None
    finally:
        use_spec_model()
    ok_gen, body = res if isinstance(res, tuple) else (True, res)
    if not body or not ok_gen:
        return None   # Clover could not produce a verified impl for our spec
    mm = re.search(r"(method\s+\w+.*)", body, re.S)
    return mm.group(1) if mm else body


def keyfree_c(parts, head, gen_ens_lines):
    method = clover_body(head, gen_ens_lines)
    if method is None:
        return None
    return V.measure_completeness(parts, method, V.ensures_list("method _() returns ()\n  " + gen_ens_lines))


def keyfree_c_mut(head, gen_ens_lines, maxn=8):
    """type-general key-free completeness via program mutation: build the full method
    (sig + generated ensures + Clover's verified body), mutate body operators, and measure
    the fraction of mutants the spec rejects. Works for any return type."""
    method = clover_body(head, gen_ens_lines)   # verified head+body (no ensures)
    if method is None:
        return None
    bs = DM.body_span(method)
    if not bs:
        return None
    body_braces = method[bs[0]:bs[1]]
    full = head + "\n    " + gen_ens_lines + "\n" + body_braces
    if DM.verify(full) is not True:
        return None   # the spec+body must verify to be a valid reference
    bspan = DM.body_span(full)
    mutants = DM.make_mutants(full, bspan)
    if not mutants:
        return None
    kills = tot = 0
    for m in mutants:
        v = DM.verify(m)
        if v is None:
            continue
        tot += 1
        kills += (v is False)   # mutant rejected by the spec -> spec caught the bug
    return (kills / tot) if tot else None


def run_task(name):
    t = load_task(name)
    if not t:
        return {"task": name, "skip": "no sig/ens"}
    doc, head, parts = t
    rec = {"task": name, "arms": {}}

    # B0: Clover spec as-is
    sgl.reset_calls(); a = time.time()
    spec = clover.gen_spec_from_doc(doc, head, DAFNY, feedback_turn=3)
    gen0 = ens_only(spec)
    c0 = keyfree_c(parts, head, gen0) if gen0 else None
    r0 = reliable_gt(parts, gen0) if gen0 else None
    rec["arms"]["B0_clover"] = {"reliable": r0, "c": c0, "llm_calls": sgl.get_calls(), "time": round(time.time() - a, 1)}

    # B1: Clover + our gate
    sgl.reset_calls(); a = time.time()
    gen = gen0; c = c0
    for _ in range(GATE_ROUNDS):
        if c is None or c >= THR:
            break
        # weak -> ask Clover to strengthen via a stronger doc, then re-gen spec
        stronger_doc = (doc + "\n\nThe postcondition must be COMPLETE and TIGHT so that an incorrect "
                        "implementation cannot satisfy it. Add all necessary ensures clauses.")
        spec2 = clover.gen_spec_from_doc(stronger_doc, head, DAFNY, feedback_turn=3)
        g2 = ens_only(spec2)
        if not g2:
            break
        c2 = keyfree_c(parts, head, g2)
        gen, c = g2, c2
    r1 = reliable_gt(parts, gen) if gen else None
    rec["arms"]["B1_ours"] = {"reliable": r1, "c": c, "llm_calls": sgl.get_calls(), "time": round(time.time() - a, 1)}
    return rec


def main():
    tasks = os.environ.get("TASKS", "").strip()
    if tasks:
        names = [t.strip() for t in tasks.split(",") if t.strip()]
    else:
        names = sorted(os.path.basename(p) for p in glob.glob(CB + "/*") if os.path.isdir(p))
    LIMIT = int(os.environ.get("LIMIT", "6"))
    names = names[:LIMIT]
    OUT = os.environ.get("OUT", "/tmp/clover_gated.json")
    res = json.load(open(OUT)) if os.path.exists(OUT) else {}
    for name in names:
        if name in res:
            continue
        try:
            rec = run_task(name)
        except Exception as e:
            rec = {"task": name, "error": str(e)[:150]}
        res[name] = rec
        json.dump(res, open(OUT, "w"), indent=1)
        a = rec.get("arms", {})
        b0, b1 = a.get("B0_clover", {}), a.get("B1_ours", {})
        print("  %-18s | B0 rel=%s c=%s calls=%s | B1 rel=%s c=%s calls=%s %s" % (
            name, b0.get("reliable"), b0.get("c"), b0.get("llm_calls"),
            b1.get("reliable"), b1.get("c"), b1.get("llm_calls"),
            rec.get("skip", rec.get("error", ""))), flush=True)
    print("DONE", flush=True)


if __name__ == "__main__":
    main()
